# Not an asset: writes games/steal-a-slime/src/visuals/shared/BaseShapeData/RocketMeshes.luau, the Space Rocket's mesh
# slots for the game (BaseShapes), in the same shape as PagodaMeshes (see models/_pagoda_meshes.py):
#   boxes  every shipped mesh's box round its build origin (plot-local game axes), the goo_jar_mascot's from JarMeshes;
#   slots  floor, name, mesh, offset (x, up, z) of the build origin after scaling, `scale` (the nose, its trim and the
#          cockpit are built on floor 4 and fitted onto the top floor, as models/_base_rocket_design.py places them),
#          show ("top" / "covered" / nil), tint role, glass = true;
#   tints  per skin, per role, MeshPart.Color (sRGB 0..255).
# Run: python iterate.py models/_rocket_meshes.py --quick --no-export
import os
import re

import bpy

from models._base_design_common import floor_top
from models._goo_jar_themes import BUILT_THEMES
import models._rocket_layout as L
import models._rocket_pieces as PC

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.environ.get("GAME_DIR", os.path.join(KIT, "..", "..", "games", "steal-a-slime"))
SKINS = ("classic",) + tuple(BUILT_THEMES)
FLOORS = 4
MASCOT_SCALE = 3.0


def raw_box(objs):
    lo = [1e9, 1e9, 1e9]
    hi = [-1e9, -1e9, -1e9]
    for o in objs:
        for v in o.data.vertices:
            w = o.matrix_world @ v.co
            for i in range(3):
                lo[i] = min(lo[i], w[i])
                hi[i] = max(hi[i], w[i])
    for o in objs:
        bpy.data.objects.remove(o, do_unlink=True)
    return lo, hi


def game_box(lo, hi):
    # blender (x, y, z) -> game plot-local (x, y, z) = (x, z, y)
    return [hi[0] - lo[0], hi[2] - lo[2], hi[1] - lo[1]], [(lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2, (lo[1] + hi[1]) / 2]


boxes = {name: game_box(*raw_box(fn())) for name, fn in PC.SHIP.items()}
jar_meshes = open(os.path.join(GAME, "src", "visuals", "shared", "JarMeshes.luau"), encoding="utf-8").read()
m = re.search(r"goo_jar_mascot = \{ size = \{ ([^}]*) \}, centre = \{ ([^}]*) \} \}", jar_meshes)
boxes["goo_jar_mascot"] = ([float(v) for v in m.group(1).split(",")], [float(v) for v in m.group(2).split(",")])

slots = []


def slot(floor, name, mesh, up=0.0, scale=1.0, show=None, role=None, glass=False):
    slots.append({"floor": floor, "name": name, "mesh": mesh, "offset": [0.0, up, 0.0], "scale": scale, "show": show,
                  "role": role, "glass": glass})


def on_top(f):
    """(offset up, scale) that fit a piece built on floor 4's nose onto top floor f (the design scene's on_top)."""
    k = L.nose_k(f)
    return PC._zt(f) - PC._zt(PC.NOSE_FLOOR) * k, k


for f in range(1, FLOORS + 1):
    slot(f, "Hull", f"rocket_hull_{f}", role=f"stage_{f}")
    slot(f, "Glass", f"rocket_glass_{f}", role="glass", glass=True)
    slot(f, "Ring", f"rocket_ring_{f}", role="joint")
    slot(f, "Deck", f"rocket_deck_{f}" if f > 1 else "rocket_post", role="deck")
    if f < FLOORS:
        slot(f, "RampLook", "rocket_ramp", up=floor_top(f) - floor_top(1), show="covered", role="ramp")
    up, k = on_top(f)
    slot(f, "Nose", "rocket_nose", up=up, scale=k, show="top", role="nose")
    slot(f, "NoseTrim", "rocket_nose_trim", up=up, scale=k, show="top", role="trim")
    slot(f, "Cockpit", "rocket_cockpit", up=up, scale=k, show="top", role="glass", glass=True)
    slot(f, "MascotLook", "goo_jar_mascot", up=L.MASCOT_Z(f) + 0.1, scale=MASCOT_SCALE, show="top")
    if f > 1:
        slot(f, "Chute", f"rocket_chute_{f}", show="top", role="trim")
slot(1, "Fins", "rocket_fins", role="fin")
slot(1, "Boosters", "rocket_boosters", role="trim")

roles = sorted({s["role"] for s in slots if s["role"]})
tints = {}
for tid in SKINS:
    r = PC.roles(tid)
    tints[tid] = {role: [round(v * 255) for v in r[role][:3]] for role in roles}


def lua_vec(v, nd=3):
    return "{ " + ", ".join(f"{x:.{nd}f}" for x in v) + " }"


lines = [
    "--!strict",
    "-- Generated by shared/modeling-kit/models/_rocket_meshes.py: do not edit by hand. The Space Rocket's mesh slots",
    "-- (boxes in plot-local game axes, the slot plan per floor with scales, the skin tints per role), see BaseShapes.",
    "return {",
    "\tboxes = {",
]
for name in sorted(boxes):
    s, c = boxes[name]
    lines.append(f"\t\t{name} = {{ size = {lua_vec(s)}, centre = {lua_vec(c)} }},")
lines.append("\t},")
lines.append("\tslots = {")
for s in slots:
    extra = ""
    if s["scale"] != 1.0:
        extra += f', scale = {s["scale"]:.5f}'
    if s["show"]:
        extra += f', show = "{s["show"]}"'
    if s["role"]:
        extra += f', role = "{s["role"]}"'
    if s["glass"]:
        extra += ", glass = true"
    lines.append(f'\t\t{{ floor = {s["floor"]}, name = "{s["name"]}", mesh = "{s["mesh"]}", offset = '
                 f'{lua_vec(s["offset"])}{extra} }},')
lines.append("\t},")
lines.append("\ttints = {")
for tid in SKINS:
    row = ", ".join(f"{r} = {{ {', '.join(str(v) for v in tints[tid][r])} }}" for r in roles)
    lines.append(f"\t\t{tid} = {{ {row} }},")
lines.append("\t},")
lines.append("}")
path = os.path.join(GAME, "src", "visuals", "shared", "BaseShapeData", "RocketMeshes.luau")
with open(path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"wrote {path}: {len(boxes)} boxes, {len(slots)} slots, {len(roles)} roles x {len(SKINS)} skins")
