# Not an asset: writes games/steal-a-slime/src/visuals/shared/BaseShapeData/CarouselMeshes.luau, the Carousel Tent's
# mesh slots for the game (BaseShapes), in the same shape as PagodaMeshes (see models/_pagoda_meshes.py):
#   boxes  every shipped mesh's box round its build origin (plot-local game axes), the goo_jar_mascot's from JarMeshes;
#   slots  floor, name, mesh, offset (x, up, z) of the build origin, show ("top" / nil), tint role, glass = true;
#          a piece shared by several floors is built on its native floor (_carousel_pieces.NATIVE) and shifted up;
#   tints  per skin, per role, MeshPart.Color (sRGB 0..255).
# Also checks that every piece stays inside the plot (r <= 39).
# Run: python iterate.py models/_carousel_meshes.py --quick --no-export
import math
import os
import re

import bpy

from models._base_design_common import floor_top
from models._goo_jar_themes import BUILT_THEMES
import models._carousel_layout as L
import models._carousel_pieces as PC

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.environ.get("GAME_DIR", os.path.join(KIT, "..", "..", "games", "steal-a-slime"))
SKINS = ("classic",) + tuple(BUILT_THEMES)
FLOORS = 4
PLOT_R = 39.0
MASCOT_SCALE = 3.6  # goo_jar_mascot is 2.2 wide: 7.9 studs, inside the 8-stud MascotBall


def raw_box(name, objs):
    lo = [1e9, 1e9, 1e9]
    hi = [-1e9, -1e9, -1e9]
    far = 0.0
    for o in objs:
        for v in o.data.vertices:
            w = o.matrix_world @ v.co
            far = max(far, math.hypot(w[0], w[1]))
            for i in range(3):
                lo[i] = min(lo[i], w[i])
                hi[i] = max(hi[i], w[i])
    for o in objs:
        bpy.data.objects.remove(o, do_unlink=True)
    assert far <= PLOT_R + 1e-6, f"{name} reaches r {far:.2f} > {PLOT_R}"
    return lo, hi, far


def game_box(lo, hi):
    # blender (x, y, z) -> game plot-local (x, y, z) = (x, z, y)
    return [hi[0] - lo[0], hi[2] - lo[2], hi[1] - lo[1]], [(lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2, (lo[1] + hi[1]) / 2]


boxes = {}
for name, fn in PC.SHIP.items():
    lo, hi, far = raw_box(name, fn())
    boxes[name] = game_box(lo, hi)
    print(f"{name}: reach r {far:.2f}")
jar_meshes = open(os.path.join(GAME, "src", "visuals", "shared", "JarMeshes.luau"), encoding="utf-8").read()
m = re.search(r"goo_jar_mascot = \{ size = \{ ([^}]*) \}, centre = \{ ([^}]*) \} \}", jar_meshes)
boxes["goo_jar_mascot"] = ([float(v) for v in m.group(1).split(",")], [float(v) for v in m.group(2).split(",")])

slots = []


def slot(floor, name, mesh, up=0.0, scale=1.0, show=None, glass=False):
    role = PC.TINT.get(mesh)
    slots.append({"floor": floor, "name": name, "mesh": mesh, "offset": [0.0, up, 0.0], "scale": scale, "show": show,
                  "role": role, "glass": glass})


def shared(f, name, mesh, **kw):
    slot(f, name, mesh, up=floor_top(f) - floor_top(PC.NATIVE[mesh]), **kw)


for f in range(1, FLOORS + 1):
    top = None if f == FLOORS else "top"
    if f == 1:
        slot(f, "Room", "carousel_room_1")
        slot(f, "Glass", "carousel_glass_1", glass=True)
        slot(f, "Gold", "carousel_gold_1")
    else:
        shared(f, "Room", "carousel_room")
        shared(f, "Glass", "carousel_glass", glass=True)
        shared(f, "Gold", "carousel_gold")
        shared(f, "Deck", "carousel_deck")
        shared(f, "RampLook", "carousel_ramp")
    shared(f, "Stripes", "carousel_stripes")
    slot(f, "RoofCream", f"carousel_roof_cream_{f}", show=top)
    slot(f, "RoofStripe", f"carousel_roof_stripe_{f}", show=top)
    shared(f, "RoofGold", "carousel_roof_gold", show=top)
    slot(f, "MascotLook", "goo_jar_mascot", up=L.SPEC["MASCOT_Z"](f), scale=MASCOT_SCALE, show=top)
slot(1, "Horses", "carousel_horses")

roles = sorted({s["role"] for s in slots if s["role"]})
tints = {}
for tid in SKINS:
    r = PC.roles(tid)
    tints[tid] = {role: [round(v * 255) for v in r[role][:3]] for role in roles}


def lua_vec(v, nd=3):
    return "{ " + ", ".join(f"{x:.{nd}f}" for x in v) + " }"


lines = [
    "--!strict",
    "-- Generated by shared/modeling-kit/models/_carousel_meshes.py: do not edit by hand. The Carousel Tent's mesh",
    "-- slots (boxes in plot-local game axes, the slot plan per floor, the skin tints per role), see BaseShapes.",
    "return {",
    "\tboxes = {",
]
for name in sorted(boxes):
    s, c = boxes[name]
    lines.append(f"\t\t{name} = {{ size = {lua_vec(s)}, centre = {lua_vec(c)} }},")
lines.append("\t},")
lines.append("\tslots = {")
for s in slots:
    extra = ""
    if s["scale"] != 1.0:
        extra += f', scale = {s["scale"]:.5f}'
    if s["show"]:
        extra += f', show = "{s["show"]}"'
    if s["role"]:
        extra += f', role = "{s["role"]}"'
    if s["glass"]:
        extra += ", glass = true"
    lines.append(f'\t\t{{ floor = {s["floor"]}, name = "{s["name"]}", mesh = "{s["mesh"]}", offset = '
                 f'{lua_vec(s["offset"])}{extra} }},')
lines.append("\t},")
lines.append("\ttints = {")
for tid in SKINS:
    row = ", ".join(f"{r} = {{ {', '.join(str(v) for v in tints[tid][r])} }}" for r in roles)
    lines.append(f"\t\t{tid} = {{ {row} }},")
lines.append("\t},")
lines.append("}")
path = os.path.join(GAME, "src", "visuals", "shared", "BaseShapeData", "CarouselMeshes.luau")
with open(path, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"wrote {path}: {len(boxes)} boxes, {len(slots)} slots, {len(roles)} roles x {len(SKINS)} skins")
