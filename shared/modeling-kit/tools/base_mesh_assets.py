#!/usr/bin/env python3
"""Record and publish the other bases' meshes (CONTRACT.md §43): factory_* (and later pagoda_*) in uploaded.json.

    python tools/base_mesh_assets.py probe factory_     # fills meshId + meshSize for uploads that lack them
    python tools/base_mesh_assets.py write factory_     # writes MeshAssets.luau's base shape block

probe: one Luau Execution task (tools/probe_meshids.py's script: InsertService loads each asset and reports its
MeshPart's MeshId and Size; nothing else runs) for every <prefix>* upload without a meshId; the Open Cloud key is
loaded the way upload.py --go loads it and never printed.
write: every <prefix>* upload with a meshId and meshSize gets an entry between "-- BEGIN base shape meshes" and
"-- END base shape meshes" (not map slots, so not in NAMES: BaseShapes builds their slots at runtime).
"""
import json
import os
import re
import sys
import time

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, KIT)
RECORD = os.path.join(KIT, "uploaded.json")
MESH_ASSETS = os.path.join(KIT, "..", "..", "games", "steal-a-slime", "src", "shared", "MeshAssets.luau")
UNIVERSE, PLACE = "10770917350", "135787188192378"  # tools/probe_meshids.py


def probe(prefixes):
    import requests

    import upload

    upload.load_env_file()
    key = os.environ["ROBLOX_OPEN_CLOUD_API_KEY"]
    headers = {"x-api-key": key}
    rec = json.load(open(RECORD))
    todo = {n: e for n, e in rec.items() if n.startswith(prefixes) and not e.get("meshId")}
    if not todo:
        print("nothing to probe")
        return
    lua = "local IS=game:GetService('InsertService');local out={}\n"
    for n, e in todo.items():
        lua += (f"do local ok,m=pcall(function() return IS:LoadAsset({e['assetId']}) end) if ok then "
                f"for _,d in m:GetDescendants() do if d:IsA('MeshPart') then "
                f"table.insert(out,'{n}|'..d.MeshId..'|'..d.Size.X..'|'..d.Size.Y..'|'..d.Size.Z) end end "
                f"else table.insert(out,'{n}|ERR|'..tostring(m)) end end\n")
    lua += "return table.concat(out, string.char(10))"
    r = requests.post(f"https://apis.roblox.com/cloud/v2/universes/{UNIVERSE}/places/{PLACE}/luau-execution-session-tasks",
                      headers=headers, json={"script": lua})
    r.raise_for_status()
    path = r.json()["path"]
    for _ in range(100):
        time.sleep(3)
        t = requests.get("https://apis.roblox.com/cloud/v2/" + path, headers=headers).json()
        if t.get("state") in ("COMPLETE", "FAILED", "CANCELLED"):
            break
    if t.get("state") != "COMPLETE":
        raise SystemExit(f"probe {t.get('state')}: {t.get('error')}")
    found = 0
    for line in "\n".join(t["output"]["results"]).splitlines():
        parts = line.split("|")
        if len(parts) == 5 and parts[1] != "ERR":
            n = parts[0]
            rec[n]["meshId"] = parts[1]
            rec[n]["meshSize"] = [round(float(v), 3) for v in parts[2:5]]
            found += 1
        else:
            print("probe:", line)
    with open(RECORD, "w") as f:
        json.dump(rec, f, indent=2, sort_keys=True)
    print(f"probed {found}/{len(todo)}")


def write(prefixes):
    rec = json.load(open(RECORD))
    names = sorted(n for n, e in rec.items() if n.startswith(prefixes) and e.get("meshId") and e.get("meshSize"))
    lines = [
        "-- BEGIN base shape meshes (generated by shared/modeling-kit/tools/base_mesh_assets.py from uploaded.json): the",
        "-- other bases' pieces and their skins' themed ones, \"<piece>@<skin>\" (CONTRACT.md §43). Not map slots, so not in",
        "-- NAMES: BaseShapes builds their slots at runtime and server/MeshSwap fills them.",
    ]
    for name in names:
        e = rec[name]
        size = ", ".join(f"{v:g}" for v in e["meshSize"])
        lines.append(f'entries["{name}"] =\n\t{{ assetId = {e["assetId"]}, meshId = "{e["meshId"]}", size = {{ {size} }} }}')
    lines.append("-- END base shape meshes")
    block = "\n".join(lines) + "\n"
    src = open(MESH_ASSETS, encoding="utf-8", newline="").read()
    if "-- BEGIN base shape meshes" in src:
        src = re.sub(r"-- BEGIN base shape meshes.*?-- END base shape meshes\n", lambda m: block, src, flags=re.S)
    else:
        anchor = "-- Mystery Egg shells and nest"
        src = src.replace(anchor, block + anchor, 1)
    open(MESH_ASSETS, "w", encoding="utf-8", newline="").write(src)
    print(f"{len(names)} entries -> {os.path.relpath(MESH_ASSETS)}")
    # format like the rest of the game (CI runs stylua --check)
    try:
        import subprocess
        subprocess.run(["stylua", MESH_ASSETS], check=False, capture_output=True)
    except OSError:
        print("stylua not found: run `stylua` on MeshAssets.luau before committing")


if __name__ == "__main__":
    cmd, prefixes = sys.argv[1], tuple(sys.argv[2:])
    {"probe": probe, "write": write}[cmd](prefixes)
