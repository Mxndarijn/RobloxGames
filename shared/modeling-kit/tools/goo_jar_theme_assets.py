#!/usr/bin/env python3
"""Write the goo jar tower theme block of games/steal-a-slime/src/shared/MeshAssets.luau from uploaded.json.

Every uploaded goo jar "<piece>@<skin>" (goo_* names; the other bases' meshes are tools/base_mesh_assets.py's) with a
meshId and meshSize (upload.py --size-check, or tools/probe_meshids.py) gets an entry between the "-- BEGIN goo jar
tower themes" and "-- END goo jar tower themes" lines. tests/ThemeMeshes.spec fails when the block and uploaded.json
disagree.

    python3 tools/goo_jar_theme_assets.py
"""
import json
import os
import re

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECORD = os.path.join(KIT, "uploaded.json")
MESH_ASSETS = os.path.join(KIT, "..", "..", "games", "steal-a-slime", "src", "shared", "MeshAssets.luau")
ORDER = ["garden", "crystal", "starlight", "candy", "mushroom"]


def main():
    rec = json.load(open(RECORD))
    themes = {}
    for name, entry in rec.items():
        if name.startswith("goo_") and "@" in name and entry.get("meshId") and entry.get("meshSize"):
            themes.setdefault(name.split("@")[1], []).append(name)
    lines = [
        "-- BEGIN goo jar tower themes (generated by shared/modeling-kit/tools/goo_jar_theme_assets.py from uploaded.json):",
        "-- each plot skin's own tower pieces, \"<piece>@<skin>\" (models/_goo_jar.py, JAR_THEME), and its companions (props,",
        "-- hat). Not map slots, so not in NAMES: server/MeshSwap shows them on a plot whose PlotSkin is that skin",
        "-- (ThemeMeshes, CONTRACT.md §15).",
    ]
    for theme in sorted(themes, key=lambda t: ORDER.index(t) if t in ORDER else len(ORDER)):
        for name in sorted(themes[theme]):
            e = rec[name]
            size = ", ".join(f"{v:g}" for v in e["meshSize"])
            lines.append(f'entries["{name}"] =\n\t{{ assetId = {e["assetId"]}, meshId = "{e["meshId"]}", size = {{ {size} }} }}')
    lines.append("-- END goo jar tower themes")
    block = "\n".join(lines) + "\n"
    src = open(MESH_ASSETS, encoding="utf-8", newline="").read()
    if "-- BEGIN goo jar tower themes" in src:
        src = re.sub(r"-- BEGIN goo jar tower themes.*?-- END goo jar tower themes\n", lambda m: block, src, flags=re.S)
    else:
        anchor = "-- Mystery Egg shells and nest"
        src = src.replace(anchor, block + anchor, 1)
    open(MESH_ASSETS, "w", encoding="utf-8", newline="").write(src)
    print({t: len(v) for t, v in themes.items()}, "->", os.path.relpath(MESH_ASSETS))


if __name__ == "__main__":
    main()
