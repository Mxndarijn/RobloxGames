#!/usr/bin/env python3
"""Upload and publish the habitat layer meshes (games/steal-a-slime HABITATS.md): habitat_frame_*, habitat_theme_*,
habitat_prop_* and habitat_frame_glow.

    python tools/habitat_mesh_assets.py upload          # dry run: lists the FBXs not uploaded yet (or changed)
    python tools/habitat_mesh_assets.py upload --go     # really uploads them (needs Merijn's OK)
    python tools/habitat_mesh_assets.py probe           # fills meshId + meshSize (one Luau Execution task)
    python tools/habitat_mesh_assets.py write           # writes MeshAssets.luau's habitat block

upload: upload.py for every out/habitat_*.fbx (frames, glow, themes, props) whose sha256 differs from uploaded.json
(a changed mesh goes up as a new version of its asset). probe: tools/base_mesh_assets.py's probe for these names.
write: every uploaded habitat mesh with a meshId and meshSize gets an entry between "-- BEGIN habitat meshes" and
"-- END habitat meshes"; a theme also gets `offset` = its bbox centre from the dish centre (out/<name>.deck.json,
kit x, y -> Roblox X, Z = x, -y), which HabitatFx undoes.
"""
import glob
import hashlib
import json
import os
import re
import subprocess
import sys

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, KIT)
sys.path.insert(0, os.path.join(KIT, "tools"))
RECORD = os.path.join(KIT, "uploaded.json")
OUT = os.path.join(KIT, "out")
MESH_ASSETS = os.path.join(KIT, "..", "..", "games", "steal-a-slime", "src", "shared", "MeshAssets.luau")
PREFIXES = ("habitat_frame_", "habitat_theme_", "habitat_prop_")


def names():
    found = []
    for path in sorted(glob.glob(os.path.join(OUT, "habitat_*.fbx"))):
        name = os.path.splitext(os.path.basename(path))[0]
        if name.startswith(PREFIXES):
            found.append(name)
    return found


def sha(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()[:16]


def upload(args):
    go = "--go" in args
    rec = json.load(open(RECORD))
    todo = []
    for name in names():
        fbx = os.path.join(OUT, f"{name}.fbx")
        e = rec.get(name)
        if not e or e.get("sha256") != sha(fbx):
            todo.append((name, fbx, e))
    print(f"{len(todo)} habitat meshes to upload{'' if go else ' (dry run; --go to send)'}")
    for name, fbx, e in todo:
        cmd = [sys.executable, os.path.join(KIT, "upload.py"), fbx]
        if e and e.get("assetId"):
            cmd += ["--update", str(e["assetId"])]
        if go:
            cmd.append("--go")
            r = subprocess.run(cmd)
            if r.returncode != 0:
                raise SystemExit(f"upload failed at {name}; rerun to continue (done ones are skipped)")
        else:
            print("  " + name + (f" (new version of {e['assetId']})" if e and e.get("assetId") else ""))


def probe(args):
    import base_mesh_assets

    base_mesh_assets.probe(PREFIXES)


def write(args):
    rec = json.load(open(RECORD))
    lines = [
        "-- BEGIN habitat meshes (generated by shared/modeling-kit/tools/habitat_mesh_assets.py from uploaded.json):",
        "-- Habitats.MESHES (rarity frames, glow lip, themes, signature props). Not map slots, so not in NAMES.",
        "-- A theme's offset = its bbox centre from the dish centre (HabitatFx moves it back).",
    ]
    count = 0
    for name in sorted(n for n, e in rec.items() if n.startswith(PREFIXES) and e.get("meshId") and e.get("meshSize")):
        e = rec[name]
        size = ", ".join(f"{v:g}" for v in e["meshSize"])
        extra = ""
        deck = os.path.join(OUT, f"{name}.deck.json")
        if name.startswith("habitat_theme_") and os.path.exists(deck):
            cx, cy = json.load(open(deck))["centre"]
            extra = f", offset = {{ {round(cx, 3):g}, 0, {round(-cy, 3):g} }}"
        lines.append(f'entries["{name}"] =\n\t{{ assetId = {e["assetId"]}, meshId = "{e["meshId"]}", size = {{ {size} }}{extra} }}')
        count += 1
    lines.append("-- END habitat meshes")
    block = "\n".join(lines) + "\n"
    src = open(MESH_ASSETS, encoding="utf-8", newline="").read()
    if "-- BEGIN habitat meshes" in src:
        src = re.sub(r"-- BEGIN habitat meshes.*?-- END habitat meshes\n", lambda m: block, src, flags=re.S)
    else:
        anchor = "-- Habitat layers (Habitats.MESHES"
        assert anchor in src, "MeshAssets.luau: habitat anchor comment not found"
        i = src.index(anchor)
        j = src.index("\n", src.index("\n", i) + 1) + 1  # after the two-line anchor comment
        src = src[:j] + block + src[j:]
    open(MESH_ASSETS, "w", encoding="utf-8", newline="").write(src)
    print(f"{count} entries -> {os.path.relpath(MESH_ASSETS)}")
    subprocess.run(["stylua", MESH_ASSETS], check=False, capture_output=True)


if __name__ == "__main__":
    cmd = sys.argv[1]
    {"upload": upload, "probe": probe, "write": write}[cmd](sys.argv[2:])
