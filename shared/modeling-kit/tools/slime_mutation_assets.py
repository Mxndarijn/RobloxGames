#!/usr/bin/env python3
"""Write the slime mutation kit block of games/steal-a-slime/src/shared/MeshAssets.luau from uploaded.json.

Every uploaded recoloured species "slime_<id>_<mutation>" (tools/slime_pool_export.py --mutation, mutation = gold,
diamond or rainbow) goes into MUTATION_KITS between the "-- BEGIN slime mutation kits" and "-- END slime mutation kits"
lines. tests/SlimeMutationKits.spec fails when the block and uploaded.json disagree.

    python3 tools/slime_mutation_assets.py
"""
import json
import os
import re

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECORD = os.path.join(KIT, "uploaded.json")
MESH_ASSETS = os.path.join(KIT, "..", "..", "games", "steal-a-slime", "src", "shared", "MeshAssets.luau")
MUTATIONS = ["gold", "diamond", "rainbow"]
NAME = re.compile(r"^(slime_[a-z0-9_]+)_(" + "|".join(MUTATIONS) + r")$")


def main():
    rec = json.load(open(RECORD))
    kits = {}
    for name, entry in rec.items():
        m = NAME.match(name)
        if m and entry.get("assetId"):
            kits.setdefault(m.group(1), {})[m.group(2)] = entry["assetId"]
    lines = [
        "-- BEGIN slime mutation kits (generated by shared/modeling-kit/tools/slime_mutation_assets.py from uploaded.json):",
        "-- species kit -> its recoloured copies (Config.SHINES `kit`), uploaded as slime_<id>_<kit>.",
        "local MUTATION_KITS: { [string]: { [string]: number } } = {",
    ]
    for kit in sorted(kits):
        ids = ", ".join(f"{mu} = {kits[kit][mu]}" for mu in MUTATIONS if mu in kits[kit])
        lines.append(f"\t{kit} = {{ {ids} }},")
    lines.append("}")
    lines.append("-- END slime mutation kits")
    block = "\n".join(lines) + "\n"
    src = open(MESH_ASSETS, encoding="utf-8", newline="").read()
    pat = re.compile(r"-- BEGIN slime mutation kits.*?-- END slime mutation kits\n", re.S)
    if not pat.search(src):
        raise SystemExit("MeshAssets.luau has no slime mutation kits block")
    src = pat.sub(lambda _: block, src, count=1)
    open(MESH_ASSETS, "w", encoding="utf-8", newline="").write(src)
    print(f"{sum(len(v) for v in kits.values())} mutation kits for {len(kits)} species")


if __name__ == "__main__":
    main()
